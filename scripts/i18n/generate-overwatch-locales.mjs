for (const lang of LANGS) {
  const dict = {};
  for (const key of keys) {
    const next = translate(key, lang);
    if (next && next !== key) dict[key] = next;
  }
  for (const pack of [CORE, UI_PACK, HOME_PACK, LEFTOVER_PACK, PAGES_PACK, BLOG_PACK, BLOG_PACK_2, MORE_PACK, CHROME_PACK, FAQ_PACK]) {
    for (const [key, map] of Object.entries(pack)) {
      if (map[lang]) dict[key] = map[lang];
    }
  }
  for (const title of REQUIRED_TITLES) {
    dict[title] = dict[title] || title;
  }
  fs.writeFileSync(path.join(mapDir, `${lang}.json`), JSON.stringify(dict, null, 2) + '\n');
  fs.writeFileSync(path.join(publicDir, `${lang}.json`), JSON.stringify(dict) + '\n');
  console.log(`${lang}: ${Object.keys(dict).length} keys`);
}

