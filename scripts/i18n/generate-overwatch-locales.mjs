function translate(en, lang) {
  if (CORE[en]?.[lang]) return CORE[en][lang];
  if (UI_PACK[en]?.[lang]) return UI_PACK[en][lang];
  if (HOME_PACK[en]?.[lang]) return HOME_PACK[en][lang];
  if (LEFTOVER_PACK[en]?.[lang]) return LEFTOVER_PACK[en][lang];
  if (PAGES_PACK[en]?.[lang]) return PAGES_PACK[en][lang];
  if (BLOG_PACK[en]?.[lang]) return BLOG_PACK[en][lang];
  if (BLOG_PACK_2[en]?.[lang]) return BLOG_PACK_2[en][lang];
  if (MORE_PACK[en]?.[lang]) return MORE_PACK[en][lang];
  if (CHROME_PACK[en]?.[lang]) return CHROME_PACK[en][lang];
  if (FAQ_PACK[en]?.[lang]) return FAQ_PACK[en][lang];
  let out = en;
  const pairs = [...(GLOSSARY[lang] ?? [])].sort((a, b) => b[0].length - a[0].length);
  for (const [from, to] of pairs) {
    if (from === to || from.length < 12) continue;
    out = out.split(from).join(to);
  }
  return out;
}

